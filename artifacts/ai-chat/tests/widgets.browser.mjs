import assert from 'node:assert/strict';
import { withFixture, waitFor, delay } from './browser-harness.mjs';

await withFixture('tests/widgets.html', async ({ cdp, evaluate, navigate, requests }) => {
  const click = (selector) => evaluate(`document.querySelector(${JSON.stringify(selector)}).click()`);
  const exists = (selector) => evaluate(`!!document.querySelector(${JSON.stringify(selector)})`);
  const text = (selector) => evaluate(`document.querySelector(${JSON.stringify(selector)})?.textContent`);
  const key = async (key, code, modifiers = 0) => {
    const windowsVirtualKeyCode = ({ Enter: 13, ' ': 32, ArrowRight: 39, ArrowLeft: 37, Home: 36, End: 35 })[key] ?? 0;
    await cdp('Input.dispatchKeyEvent', { type: 'keyDown', key, code, modifiers, windowsVirtualKeyCode,
      ...(key === ' ' ? { text: ' ' } : key === 'Enter' ? { text: '\r' } : {}) });
    await cdp('Input.dispatchKeyEvent', { type: 'keyUp', key, code, modifiers, windowsVirtualKeyCode });
  };
  const send = async (prompt) => {
    await evaluate(`document.querySelector('[data-testid="input-message"]').focus()`);
    await cdp('Input.insertText', { text: prompt });
    await click('[data-testid="button-send-message"]');
  };
  const settled = () => waitFor(async () => !await exists('[data-testid="button-stop-response"]'), 'stream completion');
  const activeId = () => evaluate(`document.querySelector('[data-testid^="active-conversation-"]').dataset.testid.replace('active-conversation-','')`);
  await waitFor(() => exists('[data-testid="input-message"]'), 'app');
  assert.ok(!requests.some((url) => /quiz-view|chart-view|recharts/.test(url)), 'Widgets are not loaded on ordinary home');
  await send('Quiz me on biology');
  await waitFor(() => exists('.widget-fallback'), 'partial widget placeholder');
  assert.ok(!await exists('[data-testid="panel-workspace"]'));
  assert.ok(!await exists('.code-block'), 'No raw widget JSON/code toolbar');
  await settled();
  await waitFor(() => exists('[data-testid="quiz-biology"]'), 'biology quiz');
  const first = await activeId();
  assert.ok(!requests.some((url) => /chart-view|recharts/.test(url)), 'Quiz does not download charts');
  await evaluate(`document.querySelector('[data-testid="option-q1-b"] input').focus()`);
  await key(' ', 'Space');
  await waitFor(() => evaluate(`document.querySelector('[data-testid="option-q1-b"] input').checked && !document.querySelector('[data-testid="button-quiz-submit"]').disabled`), 'keyboard radio selection');
  await evaluate(`document.querySelector('[data-testid="button-quiz-submit"]').focus()`);
  await key('Enter', 'Enter');
  await waitFor(() => exists('[data-testid="text-quiz-feedback"]'), 'keyboard submit');
  assert.match(await text('[data-testid="text-quiz-feedback"]'), /Not quite.*Mitochondria/);
  await evaluate(`window.dispatchEvent(new Event('pagehide'))`);
  await navigate();
  await waitFor(() => exists('[data-testid="button-start-from-home"]'), 'reload');
  await click('[data-testid="button-start-from-home"]');
  await click(`[data-testid="select-conversation-${first}"]`);
  await waitFor(() => exists('[data-testid="text-quiz-feedback"]'), 'restored quiz');
  assert.match(await text('[data-testid="text-quiz-feedback"]'), /Not quite/);
  await click('[data-testid="button-quiz-next"]');
  await click('[data-testid="option-q2-a"]');
  await click('[data-testid="button-quiz-submit"]');
  await click('[data-testid="button-quiz-next"]');
  assert.match(await text('[data-testid="text-quiz-score"]'), /1.*2/);
  await click('[data-testid="button-new-chat"]');
  await send('Quiz me on biology');
  await settled();
  await waitFor(() => exists('[data-testid="quiz-biology"]'), 'second quiz');
  const second = await activeId();
  assert.notEqual(first, second);
  assert.equal(await evaluate(`document.querySelectorAll('.nx-quiz input:checked').length`), 0, 'Identical prompts are independent');
  await click('[data-testid="option-q1-a"]');
  await click('[data-testid="button-quiz-submit"]');
  await click(`[data-testid="select-conversation-${first}"]`);
  assert.match(await text('[data-testid="text-quiz-score"]'), /1.*2/);
  await click('[data-testid="button-quiz-retry"]');
  assert.equal(await evaluate(`document.querySelectorAll('.nx-quiz input:checked').length`), 0);
  await click(`[data-testid="select-conversation-${second}"]`);
  assert.match(await text('[data-testid="text-quiz-feedback"]'), /Correct/);
  await click(`[data-testid="delete-conversation-${first}"]`);
  await evaluate(`window.dispatchEvent(new Event('pagehide'))`);
  assert.equal(await evaluate(`JSON.parse(localStorage.getItem('nexo-conversation-v2:${first}')).conversation`), null, 'Deleting chat removes its progress with the record');
  await send('Graph the example growth data');
  await settled();
  await waitFor(() => exists('[data-testid="chart-growth"] .recharts-line-curve'), 'multi-series graph');
  assert.ok(!await exists('[data-testid="panel-workspace"]'), 'Charts do not open the IDE');
  assert.match(await text('[data-testid="chart-growth"] [data-testid="text-chart-provenance"]'), /Illustrative.*not measured data/);
  await click('[data-testid="button-legend-plant_b"]');
  assert.equal(await evaluate(`document.querySelector('[data-testid="button-legend-plant_b"]').getAttribute('aria-pressed')`), 'false');
  await evaluate(`document.querySelector('.nx-inspect-body').focus()`);
  await key('ArrowRight', 'ArrowRight');
  assert.match(await text('.nx-inspect-x'), /2/);
  await click('[data-testid="chart-growth"] summary');
  assert.equal(await evaluate(`document.querySelectorAll('[data-testid="chart-growth"] tbody tr').length`), 3);
  assert.match(await text('[data-testid="chart-growth"] table'), /—/);
  await send('Math plot');
  await settled();
  await waitFor(() => exists('[data-testid="chart-math"] .recharts-line-curve'), 'calculated plot');
  assert.match(await text('[data-testid="chart-math"] [data-testid="text-chart-provenance"]'), /Calculated/);
  assert.match(await text('[data-testid="chart-math"] [data-testid="list-chart-calculations"]'), /sin\(x/);
  assert.match(await text('[data-testid="chart-math"] [data-testid="list-chart-calculations"]'), /computed locally/);
  await click('[data-testid="chart-math"] summary');
  assert.equal(await evaluate(`document.querySelectorAll('[data-testid="chart-math"] tbody tr').length`), 61);
  for (const kind of ['bar', 'scatter', 'donut']) {
    await send(kind);
    await settled();
    await waitFor(() => exists(`[data-testid="chart-${kind}"] svg`), `${kind} chart`);
  }
  await click('[data-testid="chart-donut"] [data-testid="button-legend-A"]');
  assert.equal(await text('[data-testid="chart-donut"] .nx-donut-center b'), '40', 'Filtered composition total matches visible slices');
  for (const prompt of ['malformed', 'unknown', 'partial', 'unverified']) {
    await send(prompt);
    await settled();
    const body = await evaluate(`Array.from(document.querySelectorAll('.message-row.assistant')).at(-1).textContent`);
    assert.ok(!body.includes('{"version"'), 'No raw JSON/error details');
    assert.ok(!await exists('[data-testid="panel-workspace"]'));
    assert.match(body, /malformed|Unsupported|not completed|could not be verified/);
  }
  await send('ordinary question');
  await settled();
  assert.match(await evaluate(`Array.from(document.querySelectorAll('.message-row.assistant')).at(-1).textContent`), /normal Markdown answer/);
  await evaluate(`Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:async value=>window.__copied=value}})`);
  await send('code');
  await settled();
  await waitFor(() => exists('[data-testid="panel-workspace"]'), 'normal generated code workspace');
  await click('.code-block button');
  await waitFor(() => evaluate(`window.__copied === "print('plain')\\n"`), 'raw code copy preserved');
  await click('[data-testid="button-close-workspace"]');
  await cdp('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: true });
  await cdp('Emulation.setTouchEmulationEnabled', { enabled: true, maxTouchPoints: 1 });
  if (await evaluate(`document.querySelector('[data-testid="button-toggle-sidebar"]').getAttribute('aria-expanded') === 'true'`)) await click('[data-testid="button-toggle-sidebar"]');
  await send('Quiz me on biology again');
  await settled();
  await waitFor(() => exists('[data-testid="message-assistant-19"] .nx-quiz, .nx-quiz'), 'phone quiz');
  const rect = await evaluate(`(() => { const el=Array.from(document.querySelectorAll('[data-testid="option-q1-b"]')).at(-1); el.scrollIntoView({block:'center'}); const r=el.getBoundingClientRect(); return {x:r.x+r.width/2,y:r.y+r.height/2}; })()`);
  await cdp('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [rect] });
  await cdp('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  await waitFor(() => evaluate(`Array.from(document.querySelectorAll('.nx-quiz')).at(-1).querySelector('input[value="b"]').checked`), 'touch answer selection');
  assert.ok(await evaluate(`document.documentElement.scrollWidth <= innerWidth`), 'No phone overflow');
  assert.ok(await evaluate(`matchMedia('(prefers-reduced-motion: reduce)').matches`));
  const sentMetadata = await evaluate(`window.__widgetRequests.some(r=>r.messages.some(m=>'quizProgress' in m || 'id' in m))`);
  assert.equal(sentMetadata, false, 'No quiz state or client identity sent to model');
  console.log('Inline widget browser checks passed: streamed/final answers, quiz keyboard/touch/score/retry, reload, independent chats/deletion, all chart forms, series/value/table controls, malformed/partial/unknown/source rejection, Markdown/raw code/IDE and lazy loading.');
});
